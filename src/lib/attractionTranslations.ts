export const ATTRACTION_TRANSLATIONS_EN_TO_PL: Record<string, string> = Object.entries(
  ATTRACTION_TRANSLATIONS_PL_TO_EN
).reduce((acc, [pl, en]) => {
  acc[en] = pl;
  return acc;
}, {} as Record<string, string>);

/**
 * Tłumaczy nazwę atrakcji na żądany język ('pl' | 'en').
 */
export function translateAttraction(attrName: string | undefined | null, targetLang: 'pl' | 'en'): string {
  if (!attrName) return '';
  const trimmed = attrName.trim();
  if (!trimmed) return '';

  if (targetLang === 'pl') {
    if (ATTRACTION_TRANSLATIONS_EN_TO_PL[trimmed]) {
      return ATTRACTION_TRANSLATIONS_EN_TO_PL[trimmed];
    }
    const lower = trimmed.toLowerCase();
    for (const [en, pl] of Object.entries(ATTRACTION_TRANSLATIONS_EN_TO_PL)) {
      if (en.toLowerCase() === lower) return pl;
    }
    return trimmed;
  }

  // targetLang === 'en'
  if (ATTRACTION_TRANSLATIONS_PL_TO_EN[trimmed]) {
    return ATTRACTION_TRANSLATIONS_PL_TO_EN[trimmed];
  }

  const lower = trimmed.toLowerCase();
  for (const [pl, en] of Object.entries(ATTRACTION_TRANSLATIONS_PL_TO_EN)) {
    if (pl.toLowerCase() === lower) return en;
  }

  // Heurystyczny fallback dla częściowych dopasowań
  let result = trimmed;
  result = result
    .replace(/\bZamek Królewski w\b/gi, 'Royal Castle in')
    .replace(/\bZamek Królewski na\b/gi, 'Royal Castle on')
    .replace(/\bZamek\b/gi, 'Castle')
    .replace(/\bPałac\b/gi, 'Palace')
    .replace(/\bKatedra św\./gi, 'St.')
    .replace(/\bKatedra\b/gi, 'Cathedral')
    .replace(/\bBazylika św\./gi, 'St.')
    .replace(/\bBazylika\b/gi, 'Basilica')
    .replace(/\bKościół św\./gi, 'Church of St.')
    .replace(/\bKościół\b/gi, 'Church')
    .replace(/\bRynek Główny\b/gi, 'Main Market Square')
    .replace(/\bRynek\b/gi, 'Market Square')
    .replace(/\bStare Miasto\b/gi, 'Old Town')
    .replace(/\bMuzeum\b/gi, 'Museum')
    .replace(/\bDzielnica\b/gi, 'District')
    .replace(/\bWzgórze\b/gi, 'Hill')
    .replace(/\bWyspa\b/gi, 'Island')
    .replace(/\bPark Narodowy\b/gi, 'National Park')
    .replace(/\bPark\b/gi, 'Park')
    .replace(/\bOgród\b/gi, 'Garden')
    .replace(/\bOgrody\b/gi, 'Gardens')
    .replace(/\bPlaża\b/gi, 'Beach')
    .replace(/\bMost\b/gi, 'Bridge')
    .replace(/\bMolo\b/gi, 'Pier')
    .replace(/\bBrama\b/gi, 'Gate')
    .replace(/\bTarg\b/gi, 'Market')
    .replace(/\b i \b/gi, ' & ');

  return result;
}

